def first_index_on_or_after(dates: list[pd.Timestamp], date: pd.Timestamp) -> int | None:
    idx = int(np.searchsorted(np.array(dates, dtype="datetime64[ns]"), np.datetime64(pd.Timestamp(date)), side="left"))
    if idx >= len(dates):
        return None
    return idx


def bar_for_date(hist: dict[str, pd.DataFrame], symbol: str, date: pd.Timestamp) -> pd.Series | None:
    df = hist.get(symbol)
    if df is None or df.empty:
        return None
    pos = df.attrs.get("date_pos", {}).get(pd.Timestamp(date))
    if pos is not None:
        return df.iloc[int(pos)]
    idx = int(df["time"].searchsorted(pd.Timestamp(date), side="left"))
    if idx >= len(df) or pd.Timestamp(df.iloc[idx].time) != pd.Timestamp(date):
        return None
    return df.iloc[idx]


def price_at_idx(
    hist: dict[str, pd.DataFrame],
    symbol: str,
    idx: int,
    field: str,
    *,
    require_tradable: bool = False,
) -> float | None:
    df = hist.get(symbol)
    if df is None or df.empty:
        return None
    arrays = df.attrs.get("arrays")
    if arrays:
        if idx < 0 or idx >= len(arrays["close"]):
            return None
        if require_tradable and not bool(arrays["tradable"][idx]):
            return None
        px = float(arrays[field][idx])
    else:
        if idx < 0 or idx >= len(df):
            return None
        row = df.iloc[idx]
        if require_tradable and ("tradable" in row.index and not bool(row.tradable)):
            return None
        px = float(getattr(row, field))
    return px if px > 0 and np.isfinite(px) else None


def traded_value_bil_at_idx(hist: dict[str, pd.DataFrame], symbol: str, idx: int) -> float | None:
    close_px = price_at_idx(hist, symbol, idx, "close")
    volume = price_at_idx(hist, symbol, idx, "volume")
    if close_px is None or volume is None:
        return None
    # Price is stored in thousand VND; close * volume / 1e6 gives billion VND.
    value = close_px * volume / 1_000_000.0
    return value if value >= 0 and np.isfinite(value) else None


def previous_close_at_idx(hist: dict[str, pd.DataFrame], symbol: str, idx: int) -> float | None:
    if idx <= 0:
        return None
    return price_at_idx(hist, symbol, idx - 1, "close")


def portfolio_nav_idx(cash: float, lots: dict[str, list[Lot]], hist: dict[str, pd.DataFrame], idx: int, px_field: str) -> float:
    nav = float(cash)
    for symbol, symbol_lots in lots.items():
        px = price_at_idx(hist, symbol, idx, px_field)
        if px is not None:
            nav += sum(lot.shares for lot in symbol_lots) * px
    return nav


def symbol_value_idx(lots: dict[str, list[Lot]], hist: dict[str, pd.DataFrame], symbol: str, idx: int, px_field: str) -> float:
    px = price_at_idx(hist, symbol, idx, px_field)
    if px is None:
        return 0.0
    return sum(lot.shares for lot in lots.get(symbol, [])) * px


def apply_rebalance_controls_idx(
    target_weights: dict[str, float],
    lots: dict[str, list[Lot]],
    hist: dict[str, pd.DataFrame],
    idx: int,
    nav_open: float,
    *,
    rebalance_band: float = 0.0,
    max_signal_turnover: float = 0.0,
) -> dict[str, float]:
    if nav_open <= 0 or (rebalance_band <= 0 and max_signal_turnover <= 0):
        return target_weights
    symbols = set(lots) | set(target_weights)
    current_weights = {
        symbol: symbol_value_idx(lots, hist, symbol, idx, "open") / nav_open
        for symbol in symbols
    }
    adjusted: dict[str, float] = {}
    for symbol in symbols:
        current = float(current_weights.get(symbol, 0.0))
        target = float(target_weights.get(symbol, 0.0))
        if rebalance_band > 0 and abs(target - current) <= rebalance_band:
            target = current
        adjusted[symbol] = target
    if max_signal_turnover > 0:
        deltas = {symbol: float(adjusted.get(symbol, 0.0)) - float(current_weights.get(symbol, 0.0)) for symbol in symbols}
        total_turnover = sum(abs(delta) for delta in deltas.values())
        if total_turnover > max_signal_turnover:
            scale = float(max_signal_turnover) / total_turnover
            adjusted = {
                symbol: max(0.0, float(current_weights.get(symbol, 0.0)) + delta * scale)
                for symbol, delta in deltas.items()
            }
    return {symbol: weight for symbol, weight in adjusted.items() if weight > 1e-7}


def close_for_date(hist: dict[str, pd.DataFrame], symbol: str, date: pd.Timestamp) -> float | None:
    bar = bar_for_date(hist, symbol, date)
    if bar is None:
        return None
    px = float(bar.close)
    return px if px > 0 and np.isfinite(px) else None


def open_for_date(hist: dict[str, pd.DataFrame], symbol: str, date: pd.Timestamp) -> float | None:
    bar = bar_for_date(hist, symbol, date)
    if bar is None or ("tradable" in bar.index and not bool(bar.tradable)):
        return None
    px = float(bar.open)
    return px if px > 0 and np.isfinite(px) else None


def previous_close_for_symbol(hist: dict[str, pd.DataFrame], symbol: str, date: pd.Timestamp) -> float | None:
    df = hist.get(symbol)
    if df is None or df.empty:
        return None
    idx = int(df["time"].searchsorted(pd.Timestamp(date), side="left"))
    if idx <= 0 or idx >= len(df):
        return None
    px = float(df.iloc[idx - 1].close)
    return px if px > 0 and np.isfinite(px) else None


def portfolio_nav(cash: float, lots: dict[str, list[Lot]], hist: dict[str, pd.DataFrame], date: pd.Timestamp, px_field: str) -> float:
    nav = float(cash)
    for symbol, symbol_lots in lots.items():
        bar = bar_for_date(hist, symbol, date)
        if bar is None:
            continue
        px = float(getattr(bar, px_field))
        if px > 0 and np.isfinite(px):
            nav += sum(lot.shares for lot in symbol_lots) * px
    return nav


def symbol_value(lots: dict[str, list[Lot]], hist: dict[str, pd.DataFrame], symbol: str, date: pd.Timestamp, px_field: str) -> float:
    bar = bar_for_date(hist, symbol, date)
    if bar is None:
        return 0.0
    px = float(getattr(bar, px_field))
    if px <= 0 or not np.isfinite(px):
        return 0.0
    return sum(lot.shares for lot in lots.get(symbol, [])) * px


def sell_allowed(lot: Lot, current_idx: int, min_sell_sessions: int) -> bool:
    return current_idx >= lot.entry_idx + min_sell_sessions


def sell_symbol_amount(
    lots: dict[str, list[Lot]],
    symbol: str,
    amount_value: float,
    price: float,
    current_idx: int,
    current_date: pd.Timestamp,
    min_sell_sessions: int,
    sell_cost: float,
    reason: str,
    trades: list[dict],
) -> float:
    if amount_value <= 0 or price <= 0:
        return 0.0
    symbol_lots = lots.get(symbol, [])
    remaining_value = amount_value
    cash_received = 0.0
    kept: list[Lot] = []
    for lot in symbol_lots:
        if remaining_value <= 1e-12 or not sell_allowed(lot, current_idx, min_sell_sessions):
            kept.append(lot)
            continue
        lot_value = lot.shares * price
        sell_value = min(lot_value, remaining_value)
        sell_shares = sell_value / price
        lot.shares -= sell_shares
        remaining_value -= sell_value
        proceeds = sell_shares * price * (1.0 - sell_cost)
        cash_received += proceeds
        trades.append({
            "date": current_date,
            "symbol": symbol,
            "side": "SELL",
            "shares": sell_shares,
            "price": price,
            "cash": proceeds,
            "reason": reason,
            "entry_date": lot.entry_date,
            "entry_px": lot.entry_px,
            "holding_sessions": current_idx - lot.entry_idx,
        })
        if lot.shares > 1e-12:
            kept.append(lot)
    if kept:
        lots[symbol] = kept
    elif symbol in lots:
        del lots[symbol]
    return cash_received


def execute_buy_order(
    order: BuyOrder,
    lots: dict[str, list[Lot]],
    cash: float,
    hist: dict[str, pd.DataFrame],
    date: pd.Timestamp,
    current_idx: int,
    buy_cost: float,
    trades: list[dict],
) -> tuple[float, bool, str]:
    bar = bar_for_date(hist, order.symbol, date)
    if bar is None or ("tradable" in bar.index and not bool(bar.tradable)):
        return cash, False, "missing_bar"
    open_px = float(bar.open)
    if open_px <= 0 or not np.isfinite(open_px):
        return cash, False, "bad_open"

    fill_px = None
    fill_mode = ""
    if not order.first_day_seen:
        order.first_day_seen = True
        prev_close = order.prev_close
        if prev_close and prev_close > 0:
            gap = open_px / prev_close - 1.0
            if gap <= order.gap_threshold:
                fill_px = open_px
                fill_mode = "open"

    if fill_px is None and order.prev_close and order.prev_close > 0:
        limit_px = order.prev_close * (1.0 + order.limit_buffer)
        low_px = float(bar.low)
        if low_px <= limit_px:
            fill_px = min(open_px, limit_px) if open_px <= limit_px else limit_px
            fill_mode = "pullback_limit"

    if fill_px is None:
        return cash, False, "waiting"

    spend = min(float(order.cash_amount), cash)
    if spend <= 1e-9:
        return cash, True, "no_cash"
    shares = spend / (fill_px * (1.0 + buy_cost))
    total_cost = shares * fill_px * (1.0 + buy_cost)
    cash -= total_cost
    lot = Lot(order.symbol, shares, current_idx, pd.Timestamp(date), float(fill_px))
    lots.setdefault(order.symbol, []).append(lot)
    trades.append({
        "date": date,
        "symbol": order.symbol,
        "side": "BUY",
        "shares": shares,
        "price": fill_px,
        "cash": -total_cost,
        "reason": fill_mode,
        "entry_date": date,
        "entry_px": fill_px,
        "holding_sessions": 0,
    })
    return cash, True, fill_mode


def execute_buy_order_idx(
    order: BuyOrder,
    lots: dict[str, list[Lot]],
    cash: float,
    hist: dict[str, pd.DataFrame],
    date: pd.Timestamp,
    current_idx: int,
    buy_cost: float,
    trades: list[dict],
) -> tuple[float, bool, str]:
    open_px = price_at_idx(hist, order.symbol, current_idx, "open", require_tradable=True)
    if open_px is None:
        return cash, False, "missing_bar"
    if float(order.min_execution_value_bil or 0.0) > 0:
        traded_value = traded_value_bil_at_idx(hist, order.symbol, current_idx)
        if traded_value is None or traded_value < float(order.min_execution_value_bil):
            return cash, False, "low_liq"
    if float(order.max_participation or 0.0) > 0:
        traded_value = traded_value_bil_at_idx(hist, order.symbol, current_idx)
        scaled_order_value = float(order.cash_amount) * float(order.nav_scale_bil or 1.0)
        if traded_value is None or traded_value <= 0 or scaled_order_value > traded_value * float(order.max_participation):
            return cash, False, "low_liq"

    fill_px = None
    fill_mode = ""
    if not order.first_day_seen:
        order.first_day_seen = True
        prev_close = order.prev_close
        if prev_close and prev_close > 0:
            gap = open_px / prev_close - 1.0
            if gap <= order.gap_threshold:
                fill_px = open_px
                fill_mode = "open"

    if fill_px is None and order.prev_close and order.prev_close > 0:
        limit_px = order.prev_close * (1.0 + order.limit_buffer)
        low_px = price_at_idx(hist, order.symbol, current_idx, "low")
        if low_px is not None and low_px <= limit_px:
            fill_px = min(open_px, limit_px) if open_px <= limit_px else limit_px
            fill_mode = "pullback_limit"

    if fill_px is None:
        return cash, False, "waiting"

    spend = min(float(order.cash_amount), cash)
    if spend <= 1e-9:
        return cash, True, "no_cash"
    shares = spend / (fill_px * (1.0 + buy_cost))
    total_cost = shares * fill_px * (1.0 + buy_cost)
    cash -= total_cost
    lot = Lot(order.symbol, shares, current_idx, pd.Timestamp(date), float(fill_px))
    lots.setdefault(order.symbol, []).append(lot)
    trades.append({
        "date": date,
        "symbol": order.symbol,
        "side": "BUY",
        "shares": shares,
        "price": fill_px,
        "cash": -total_cost,
        "reason": fill_mode,
        "entry_date": date,
        "entry_px": fill_px,
        "holding_sessions": 0,
    })
    return cash, True, fill_mode


