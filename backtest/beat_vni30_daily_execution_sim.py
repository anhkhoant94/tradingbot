def align_history_to_calendar(hist: dict[str, pd.DataFrame], dates: list[pd.Timestamp]) -> dict[str, pd.DataFrame]:
    """Forward-fill valuation prices while preserving tradability flags."""
    calendar = pd.DataFrame({"time": pd.to_datetime(dates)})
    aligned = {}
    for symbol, df in hist.items():
        x = calendar.merge(df.assign(tradable=True), on="time", how="left")
        x["tradable"] = x["tradable"].eq(True)
        x["close"] = pd.to_numeric(x["close"], errors="coerce").ffill()
        for col in ["open", "high", "low"]:
            x[col] = pd.to_numeric(x[col], errors="coerce").fillna(x["close"])
        x["volume"] = pd.to_numeric(x["volume"], errors="coerce").fillna(0.0)
        x = x.reset_index(drop=True)
        x.attrs["date_pos"] = {pd.Timestamp(d): i for i, d in enumerate(x["time"])}
        x.attrs["arrays"] = {
            "open": x["open"].to_numpy(dtype=float),
            "high": x["high"].to_numpy(dtype=float),
            "low": x["low"].to_numpy(dtype=float),
            "close": x["close"].to_numpy(dtype=float),
            "volume": x["volume"].to_numpy(dtype=float),
            "tradable": x["tradable"].to_numpy(dtype=bool),
        }
        aligned[symbol] = x
    return aligned


