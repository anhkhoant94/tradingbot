"""Daily execution simulator for the flexible VNI+30 candidate.

This is stricter than the weekly return proxy. Weekly target portfolios are
still generated by ``pass30_direct_search.run_policy`` from point-in-time
signals, but orders are executed on daily bars with:

- Monday/open-or-pullback buy logic.
- Pending buy windows that can extend beyond Wednesday.
- Per-lot T+2.5 sell availability, approximated conservatively as the third
  trading session after entry for open-price exits.
- Optional daily stop loss after a lot becomes sellable.

The simulator keeps cash and shares, so late fills do not double-count returns
or reuse capital before the position can be sold.
"""
