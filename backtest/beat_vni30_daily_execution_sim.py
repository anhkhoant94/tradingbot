def simulate_daily(
    holdings: pd.DataFrame,
    hist: dict[str, pd.DataFrame],
    vni: pd.DataFrame,
    *,
    gap_threshold: float,
    limit_buffer: float,
    pullback_sessions: int,
    min_sell_sessions: int,
    daily_stop_loss: float,
    extra_slippage_per_side: float,
    signal_dates: list[pd.Timestamp] | None = None,
    nav0: float = 1.0,
    portfolio_vs_vni_brake_5d: float = 0.0,
    portfolio_vs_vni_brake_mult: float = 0.50,
    portfolio_vs_vni_brake_min_exposure: float = 0.80,
    portfolio_vs_vni_brake_cooldown_signals: int = 2,
    portfolio_loss_brake_5d: float = 0.0,
    min_execution_value_bil: float = 0.0,
    max_participation: float = 0.0,
    nav_scale_bil: float = 1.0,
    rebalance_band: float = 0.0,
    max_signal_turnover: float = 0.0,
    limit_floor_buffer: float | None = None,
    limit_tranches: int = 1,
    daily_max_weight_cap: float = 0.0,
) -> tuple[pd.DataFrame, pd.DataFrame, dict]:
    if signal_dates is None:
        signal_dates = sorted(pd.Timestamp(x) for x in holdings["date"].dropna().unique())
    else:
        signal_dates = sorted(pd.Timestamp(x) for x in signal_dates)
    if not signal_dates:
        return pd.DataFrame(), pd.DataFrame(), {}
    start = signal_dates[0]
    end = signal_dates[-1]
    vni_full = vni.copy()
    vni = vni[(vni["date"] >= start) & (vni["date"] <= end)].copy()
    daily_dates = [pd.Timestamp(x) for x in vni["date"].tolist()]
    signal_idx_by_date = {d: i for i, d in enumerate(signal_dates)}
    signal_dates_set = set(signal_dates)
    targets_by_date = {
        pd.Timestamp(date): dict(zip(group["symbol"].astype(str), group["weight"].astype(float)))
        for date, group in holdings.groupby("date", sort=False)
    }

    cash = float(nav0)
    lots: dict[str, list[Lot]] = {}
    pending_buys: list[BuyOrder] = []
    rows: list[dict] = []
    trades: list[dict] = []
    buy_cost = 0.0015 + float(extra_slippage_per_side)
    sell_cost = 0.0025 + float(extra_slippage_per_side)
    exchange_map = load_exchange_map()
    vni_close_arr = vni["close"].astype(float).to_numpy()
    brake_signal_cooldown = 0
    brake_daily_cooldown_until = -1

    for current_idx, date in enumerate(daily_dates):
        is_signal_day = date in signal_dates_set
        if (
            (portfolio_vs_vni_brake_5d < 0 or portfolio_loss_brake_5d < 0)
            and len(rows) >= 6
            and current_idx >= 6
            and current_idx > brake_daily_cooldown_until
        ):
            nav_now = float(rows[-1]["nav"])
            nav_prev = float(rows[-6]["nav"])
            vni_now = float(vni_close_arr[current_idx - 1])
            vni_prev = float(vni_close_arr[current_idx - 6])
            current_exposure = float(rows[-1]["exposure"])
            if nav_prev > 0 and vni_prev > 0:
                portfolio_5d = nav_now / nav_prev - 1.0
                rel_5d = portfolio_5d - (vni_now / vni_prev - 1.0)
                edge_trigger = portfolio_vs_vni_brake_5d < 0 and rel_5d <= float(portfolio_vs_vni_brake_5d)
                loss_trigger = portfolio_loss_brake_5d < 0 and portfolio_5d <= float(portfolio_loss_brake_5d)
                if (edge_trigger or loss_trigger) and current_exposure >= float(portfolio_vs_vni_brake_min_exposure):
                    nav_open_for_brake = portfolio_nav_idx(cash, lots, hist, current_idx, "open")
                    target_exposure_value = nav_open_for_brake * current_exposure * float(portfolio_vs_vni_brake_mult)
                    current_exposure_value = nav_open_for_brake * current_exposure
                    sell_ratio = 0.0
                    if current_exposure_value > 0 and target_exposure_value < current_exposure_value:
                        sell_ratio = 1.0 - target_exposure_value / current_exposure_value
                    for symbol in list(lots):
                        open_px = price_at_idx(hist, symbol, current_idx, "open", require_tradable=True)
                        if open_px is None:
                            continue
                        symbol_val = symbol_value_idx(lots, hist, symbol, current_idx, "open")
                        cash += sell_symbol_amount(
                            lots,
                            symbol,
                            symbol_val * sell_ratio,
                            open_px,
                            current_idx,
                            date,
                            min_sell_sessions,
                            sell_cost,
                            "portfolio_brake",
                            trades,
                        )
                    brake_signal_cooldown = max(brake_signal_cooldown, int(portfolio_vs_vni_brake_cooldown_signals))
                    brake_daily_cooldown_until = current_idx + max(1, int(portfolio_vs_vni_brake_cooldown_signals)) * 5
        if is_signal_day:
            pending_buys = []
            if (
                (portfolio_vs_vni_brake_5d < 0 or portfolio_loss_brake_5d < 0)
                and len(rows) >= 6
                and current_idx >= 6
            ):
                nav_now = float(rows[-1]["nav"])
                nav_prev = float(rows[-6]["nav"])
                vni_now = float(vni_close_arr[current_idx - 1])
                vni_prev = float(vni_close_arr[current_idx - 6])
                current_exposure = float(rows[-1]["exposure"])
                if nav_prev > 0 and vni_prev > 0:
                    portfolio_5d = nav_now / nav_prev - 1.0
                    rel_5d = portfolio_5d - (vni_now / vni_prev - 1.0)
                    edge_trigger = portfolio_vs_vni_brake_5d < 0 and rel_5d <= float(portfolio_vs_vni_brake_5d)
                    loss_trigger = portfolio_loss_brake_5d < 0 and portfolio_5d <= float(portfolio_loss_brake_5d)
                    if (edge_trigger or loss_trigger) and current_exposure >= float(portfolio_vs_vni_brake_min_exposure):
                        brake_signal_cooldown = max(brake_signal_cooldown, int(portfolio_vs_vni_brake_cooldown_signals))
            target_weights = targets_by_date.get(date, {})
            if brake_signal_cooldown > 0 and target_weights:
                target_weights = {symbol: weight * float(portfolio_vs_vni_brake_mult) for symbol, weight in target_weights.items()}
                brake_signal_cooldown -= 1
            nav_open = portfolio_nav_idx(cash, lots, hist, current_idx, "open")
            target_weights = apply_rebalance_controls_idx(
                target_weights,
                lots,
                hist,
                current_idx,
                nav_open,
                rebalance_band=rebalance_band,
                max_signal_turnover=max_signal_turnover,
            )
            current_symbols = set(lots) | set(target_weights)

            for symbol in sorted(current_symbols):
                open_px = price_at_idx(hist, symbol, current_idx, "open", require_tradable=True)
                if open_px is None:
                    continue
                cur_value = symbol_value_idx(lots, hist, symbol, current_idx, "open")
                target_value = nav_open * float(target_weights.get(symbol, 0.0))
                if cur_value > target_value + nav_open * 0.001:
                    cash += sell_symbol_amount(
                        lots,
                        symbol,
                        cur_value - target_value,
                        open_px,
                        current_idx,
                        date,
                        min_sell_sessions,
                        sell_cost,
                        "rebalance",
                        trades,
                    )

            nav_after_sells = portfolio_nav_idx(cash, lots, hist, current_idx, "open")
            buy_specs = []
            for symbol, weight in sorted(target_weights.items(), key=lambda kv: -kv[1]):
                cur_value = symbol_value_idx(lots, hist, symbol, current_idx, "open")
                target_value = nav_after_sells * float(weight)
                buy_value = max(0.0, target_value - cur_value)
                if buy_value > nav_after_sells * 0.001:
                    buy_specs.append((symbol, buy_value))
            total_buy = sum(v for _, v in buy_specs)
            scale = min(1.0, cash / total_buy) if total_buy > 0 else 0.0
            for symbol, buy_value in buy_specs:
                start_idx = current_idx
                deadline_idx = min(len(daily_dates) - 1, current_idx + max(1, pullback_sessions) - 1)
                prev_close = previous_close_at_idx(hist, symbol, current_idx)
                tranche_count = max(1, int(limit_tranches or 1))
                if tranche_count == 1:
                    levels = [float(limit_buffer)]
                else:
                    floor = float(limit_floor_buffer if limit_floor_buffer is not None else limit_buffer)
                    levels = [float(x) for x in np.linspace(float(limit_buffer), floor, tranche_count)]
                for level in levels:
                    pending_buys.append(BuyOrder(
                        symbol=symbol,
                        cash_amount=buy_value * scale / tranche_count,
                        signal_date=date,
                        start_idx=start_idx,
                        deadline_idx=deadline_idx,
                        gap_threshold=effective_gap_threshold(symbol, level, exchange_map),
                        limit_buffer=level,
                        prev_close=prev_close,
                        min_execution_value_bil=float(min_execution_value_bil),
                        max_participation=float(max_participation),
                        nav_scale_bil=float(nav_scale_bil),
                    ))

        still_pending = []
        for order in pending_buys:
            if current_idx < order.start_idx:
                still_pending.append(order)
                continue
            if current_idx > order.deadline_idx:
                trades.append({
                    "date": date,
                    "symbol": order.symbol,
                    "side": "MISS_BUY",
                    "shares": 0.0,
                    "price": np.nan,
                    "cash": 0.0,
                    "reason": "expired_no_pullback",
                    "entry_date": pd.NaT,
                    "entry_px": np.nan,
                    "holding_sessions": 0,
                })
                continue
            cash, done, reason = execute_buy_order_idx(order, lots, cash, hist, date, current_idx, buy_cost, trades)
            if not done and reason in {"waiting", "low_liq"}:
                still_pending.append(order)
        pending_buys = still_pending

        if daily_stop_loss > 0:
            for symbol in list(lots):
                if price_at_idx(hist, symbol, current_idx, "open", require_tradable=True) is None:
                    continue
                kept: list[Lot] = []
                stop_cash = 0.0
                for lot in lots.get(symbol, []):
                    if not sell_allowed(lot, current_idx, min_sell_sessions):
                        kept.append(lot)
                        continue
                    stop_px = lot.entry_px * (1.0 - daily_stop_loss)
                    open_px = price_at_idx(hist, symbol, current_idx, "open") or 0.0
                    low_px = price_at_idx(hist, symbol, current_idx, "low") or np.inf
                    if low_px <= stop_px:
                        fill_px = open_px if open_px <= stop_px else stop_px
                        proceeds = lot.shares * fill_px * (1.0 - sell_cost)
                        stop_cash += proceeds
                        trades.append({
                            "date": date,
                            "symbol": symbol,
                            "side": "SELL",
                            "shares": lot.shares,
                            "price": fill_px,
                            "cash": proceeds,
                            "reason": "daily_stop",
                            "entry_date": lot.entry_date,
                            "entry_px": lot.entry_px,
                            "holding_sessions": current_idx - lot.entry_idx,
                        })
                    else:
                        kept.append(lot)
                cash += stop_cash
                if kept:
                    lots[symbol] = kept
                elif symbol in lots:
                    del lots[symbol]

        if daily_max_weight_cap and daily_max_weight_cap > 0:
            nav_close_for_cap = portfolio_nav_idx(cash, lots, hist, current_idx, "close")
            if nav_close_for_cap > 0:
                for symbol in list(lots):
                    close_px = price_at_idx(hist, symbol, current_idx, "close", require_tradable=True)
                    if close_px is None:
                        continue
                    symbol_val = symbol_value_idx(lots, hist, symbol, current_idx, "close")
                    allowed_value = nav_close_for_cap * float(daily_max_weight_cap)
                    if symbol_val > allowed_value + nav_close_for_cap * 0.001:
                        cash += sell_symbol_amount(
                            lots,
                            symbol,
                            symbol_val - allowed_value,
                            close_px,
                            current_idx,
                            date,
                            min_sell_sessions,
                            sell_cost,
                            "daily_weight_cap",
                            trades,
                        )

        nav_close = portfolio_nav_idx(cash, lots, hist, current_idx, "close")
        exposure = 0.0
        for symbol in lots:
            exposure += symbol_value_idx(lots, hist, symbol, current_idx, "close")
        exposure = exposure / nav_close if nav_close > 0 else 0.0
        rows.append({
            "date": date,
            "nav": nav_close,
            "cash": cash,
            "exposure": exposure,
            "pending_buy_count": len(pending_buys),
            "position_count": len(lots),
            "is_signal_day": is_signal_day,
            "signal_seq": signal_idx_by_date.get(date, np.nan),
        })

    eq = pd.DataFrame(rows)
    if not eq.empty:
        eq["strat_ret_5d"] = eq["nav"].astype(float).pct_change(5)
        if len(vni) == len(eq):
            eq["vni_ret_5d"] = vni["close"].astype(float).reset_index(drop=True).pct_change(5)
    trades_df = pd.DataFrame(trades)
    metrics = add_daily_vni30_metrics(eq, vni, canonical_vni=vni_full)
    return eq, trades_df, metrics


def add_daily_vni30_metrics(eq: pd.DataFrame, vni: pd.DataFrame, canonical_vni: pd.DataFrame | None = None) -> dict:
    eq = eq.copy()
    eq["date"] = pd.to_datetime(eq["date"])
    eq = eq.sort_values("date").reset_index(drop=True)
    if canonical_vni is None:
        canonical_vni = vni
    canonical_vni = canonical_vni.copy()
    canonical_vni["date"] = pd.to_datetime(canonical_vni["date"])
    canonical_vni = canonical_vni.sort_values("date").reset_index(drop=True)
    yearly = {}
    for year, group in eq.groupby(eq["date"].dt.year):
        year = int(year)
        if 2021 <= year <= 2026 and len(group) > 1:
            prev = eq[eq["date"] < pd.Timestamp(f"{year}-01-01")]
            base_nav = float(prev["nav"].iloc[-1]) if not prev.empty else float(group["nav"].iloc[0])
            if base_nav > 0:
                yearly[year] = (float(group["nav"].iloc[-1]) / base_nav - 1.0) * 100.0
    vni_ret = {}
    for year in range(2021, 2027):
        eq_group = eq[eq["date"].dt.year == year]
        if eq_group.empty:
            continue
        end_date = pd.Timestamp(eq_group["date"].iloc[-1])
        prev_vni = canonical_vni[canonical_vni["date"] < pd.Timestamp(f"{year}-01-01")]
        year_vni = canonical_vni[
            (canonical_vni["date"].dt.year == year)
            & (canonical_vni["date"] <= end_date)
        ]
        if year_vni.empty:
            continue
        base_close = float(prev_vni["close"].iloc[-1]) if not prev_vni.empty else float(year_vni["close"].iloc[0])
        if base_close > 0:
            vni_ret[year] = (float(year_vni["close"].iloc[-1]) / base_close - 1.0) * 100.0
    nav = eq["nav"].astype(float)
    ret = nav.pct_change().fillna(0.0)
    yrs = (eq["date"].iloc[-1] - eq["date"].iloc[0]).days / 365.25
    cagr = (nav.iloc[-1] / nav.iloc[0]) ** (1 / yrs) - 1 if yrs > 0 and nav.iloc[0] > 0 else np.nan
    maxdd = (nav / nav.cummax() - 1).min()
    sharpe = ret.mean() / ret.std() * np.sqrt(252) if ret.std() > 0 else 0.0
    metrics = {
        "cagr": cagr * 100.0,
        "maxdd": maxdd * 100.0,
        "sharpe": float(sharpe),
        "pass30": 0,
        "pass_vni30": 0,
        "min_edge_vs_vni": np.nan,
        "min_gap_to_vni30": np.nan,
    }
    edges = []
    pass30 = 0
    pass_vni30 = 0
    for year in range(2021, 2027):
        strategy = float(yearly.get(year, np.nan))
        vni_y = float(vni_ret.get(year, np.nan))
        edge = strategy - vni_y if pd.notna(strategy) and pd.notna(vni_y) else np.nan
        metrics[f"y{year}"] = strategy
        metrics[f"vni_y{year}"] = vni_y
        metrics[f"edge_y{year}"] = edge
        metrics[f"pass_vni30_y{year}"] = bool(pd.notna(edge) and edge >= 30.0)
        if pd.notna(strategy) and strategy >= 30.0:
            pass30 += 1
        if pd.notna(edge):
            edges.append(edge)
            if edge >= 30.0:
                pass_vni30 += 1
    metrics["pass30"] = pass30
    metrics["pass_vni30"] = pass_vni30
    if edges:
        metrics["min_edge_vs_vni"] = float(min(edges))
        metrics["min_gap_to_vni30"] = float(min(edges) - 30.0)
    return metrics


