def atomic_temp_path(path: Path) -> Path:
    return path.with_name(f".{path.stem}.{os.getpid()}.tmp{path.suffix}")


def fsync_file(path: Path) -> None:
    with path.open("r+b") as handle:
        os.fsync(handle.fileno())


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = atomic_temp_path(path)
    with tmp.open("w", encoding="utf-8") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    tmp.replace(path)


def atomic_write_csv(df: pd.DataFrame, path: Path, **kwargs) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = atomic_temp_path(path)
    df.to_csv(tmp, **kwargs)
    fsync_file(tmp)
    tmp.replace(path)


def atomic_write_parquet(df: pd.DataFrame, path: Path, **kwargs) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = atomic_temp_path(path)
    df.to_parquet(tmp, **kwargs)
    fsync_file(tmp)
    tmp.replace(path)


def verify_saved_outputs(best_dir: Path, best: dict) -> bool:
    try:
        eq = pd.read_parquet(best_dir / "equity_curve_honest.parquet")
        if len(eq) < 1000 or "nav" not in eq.columns:
            return False
        if not np.isfinite(pd.to_numeric(eq["nav"], errors="coerce").iloc[-1]):
            return False
        payload = json.loads((best_dir / "config.json").read_text(encoding="utf-8"))
        return int(payload.get("metrics", {}).get("pass_vni30", -1)) == int(best.get("metrics", {}).get("pass_vni30", -2))
    except Exception:
        return False


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_hash_chain(best_dir: Path) -> bool:
    sums = best_dir / "sha256sums.txt"
    if not sums.exists():
        return False
    for raw in sums.read_text(encoding="utf-8").splitlines():
        if not raw.strip():
            continue
        parts = raw.split()
        if len(parts) < 3:
            return False
        expected_hash, name, expected_size = parts[0], parts[1], int(parts[2])
        path = best_dir / name
        if not path.exists() or path.stat().st_size != expected_size:
            return False
        if sha256_file(path) != expected_hash:
            return False
    return True


def verify_json_files(best_dir: Path, names: list[str]) -> bool:
    for name in names:
        path = best_dir / name
        if path.exists():
            try:
                json.loads(path.read_text(encoding="utf-8"))
            except Exception:
                return False
    return True


def write_companion_integrity_files(best_dir: Path, best: dict, best_eq: pd.DataFrame, best_trades: pd.DataFrame) -> None:
    metrics = dict(best.get("metrics", {}))
    eq_sorted = best_eq.copy()
    if len(eq_sorted) and "date" in eq_sorted:
        eq_sorted["date"] = pd.to_datetime(eq_sorted["date"])
        eq_sorted = eq_sorted.sort_values("date").reset_index(drop=True)
    equity_summary = {
        "rows": int(len(best_eq)),
        "start_date": str(eq_sorted["date"].iloc[0]) if len(eq_sorted) and "date" in eq_sorted else None,
        "end_date": str(eq_sorted["date"].iloc[-1]) if len(eq_sorted) and "date" in eq_sorted else None,
        "start_nav": float(eq_sorted["nav"].iloc[0]) if len(eq_sorted) and "nav" in eq_sorted else None,
        "end_nav": float(eq_sorted["nav"].iloc[-1]) if len(eq_sorted) and "nav" in eq_sorted else None,
        "avg_exposure": float(eq_sorted["exposure"].mean()) if len(eq_sorted) and "exposure" in eq_sorted else None,
        "max_exposure": float(eq_sorted["exposure"].max()) if len(eq_sorted) and "exposure" in eq_sorted else None,
        "min_cash": float(eq_sorted["cash"].min()) if len(eq_sorted) and "cash" in eq_sorted else None,
    }
    trade_summary = {
        "rows": int(len(best_trades)),
        "first_date": str(best_trades["date"].iloc[0]) if len(best_trades) and "date" in best_trades else None,
        "last_date": str(best_trades["date"].iloc[-1]) if len(best_trades) and "date" in best_trades else None,
        "side_counts": best_trades["side"].astype(str).value_counts().to_dict() if len(best_trades) and "side" in best_trades else {},
        "reason_counts": best_trades["reason"].astype(str).value_counts().to_dict() if len(best_trades) and "reason" in best_trades else {},
    }
    companion = {
        "strategy_type": best.get("strategy_type"),
        "metrics": metrics,
        "execution": best.get("execution", {}),
        "stress": best.get("stress", {}),
        "vni_yearly_convention": best.get("vni_yearly_convention"),
        "equity_summary": equity_summary,
        "trade_summary": trade_summary,
    }
    atomic_write_text(best_dir / "metrics.json", json.dumps(companion, indent=2, default=str))
    yearly_rows = []
    if len(eq_sorted) and "date" in eq_sorted and "nav" in eq_sorted:
        for year in range(2021, 2027):
            group = eq_sorted[eq_sorted["date"].dt.year == year]
            if group.empty:
                continue
            prev = eq_sorted[eq_sorted["date"] < pd.Timestamp(f"{year}-01-01")]
            start_nav = float(prev["nav"].iloc[-1]) if not prev.empty else float(group["nav"].iloc[0])
            end_nav = float(group["nav"].iloc[-1])
            yearly_rows.append({
                "year": year,
                "start_date": str(group["date"].iloc[0]),
                "end_date": str(group["date"].iloc[-1]),
                "start_nav": start_nav,
                "end_nav": end_nav,
                "strategy_return_pct": metrics.get(f"y{year}"),
                "vni_return_pct": metrics.get(f"vni_y{year}"),
                "edge_vs_vni_pp": metrics.get(f"edge_y{year}"),
                "pass_vni30": metrics.get(f"pass_vni30_y{year}"),
            })
    atomic_write_text(
        best_dir / "equity_curve_yearly.json",
        json.dumps(
            {
                "vni_yearly_convention": best.get("vni_yearly_convention"),
                "rows": yearly_rows,
            },
            indent=2,
            default=str,
        ),
    )
    files = [
        "config.json",
        "daily_execution_trades.csv",
        "equity_curve_honest.parquet",
        "metrics.json",
        "equity_curve_yearly.json",
    ]
    lines = []
    for name in files:
        path = best_dir / name
        if path.exists():
            lines.append(f"{sha256_file(path)}  {name}  {path.stat().st_size}")
    atomic_write_text(best_dir / "sha256sums.txt", "\n".join(lines) + "\n")
    time.sleep(3.0)
    if not verify_json_files(best_dir, ["config.json", "metrics.json", "equity_curve_yearly.json"]):
        raise IOError(f"artifact json verification failed: {best_dir}")
    if not verify_hash_chain(best_dir):
        raise IOError(f"artifact hash verification failed: {best_dir}")


