def normalize_exchange(value) -> str:
    raw = str(value or "").upper().replace(" ", "")
    if raw in {"UPCO", "UPCOM", "UPC"}:
        return "UPCOM"
    return raw


def load_exchange_map() -> dict[str, str]:
    path = ROOT / ".cache" / "universe.parquet"
    if not path.exists():
        return {}
    try:
        df = pd.read_parquet(path)
    except Exception:
        return {}
    if "symbol" not in df.columns or "exchange" not in df.columns:
        return {}
    return {
        str(row.symbol).upper(): normalize_exchange(row.exchange)
        for row in df[["symbol", "exchange"]].dropna().itertuples(index=False)
    }


def effective_gap_threshold(symbol: str, base_gap: float, exchange_map: dict[str, str]) -> float:
    if float(base_gap) < 0:
        return float(base_gap)
    exchange = exchange_map.get(str(symbol or "").upper(), "")
    limit = PRICE_LIMIT_BY_EXCHANGE.get(exchange)
    if limit is None:
        return float(base_gap)
    return max(0.0, min(float(base_gap), limit - PRICE_LIMIT_GUARD))


def load_daily_history(symbols: list[str]) -> dict[str, pd.DataFrame]:
    hist = {}
    # 2026-05-27 override: set HISTORY_CACHE_DIR=history_2012 to use refreshed data
